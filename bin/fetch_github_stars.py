#!/usr/bin/env python3
"""Collect star counts for every GitHub repo linked from the bibliography.

Writes _data/github_stars.yml, which _layouts/bib.liquid reads to put a star
count on each Code button. Regenerated by the deploy workflow on every build,
so the committed copy only needs to be good enough for local previews.

Set GITHUB_TOKEN to lift the 60 requests/hour anonymous rate limit.
"""

import json
import os
import re
import sys
import urllib.error
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIB = os.path.join(ROOT, "_bibliography", "papers.bib")
OUT = os.path.join(ROOT, "_data", "github_stars.yml")

REPO_RE = re.compile(r"github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+?)(?:\.git)?[/\s,}\"']")


def repos_in_bibliography(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    seen = {}
    for owner, name in REPO_RE.findall(text):
        # github.io pages and the bibliography's own links are not repos we star.
        if owner.lower() in {"alshedivat"} or name.endswith(".github.io"):
            continue
        seen.setdefault(f"{owner}/{name}", None)
    return sorted(seen)


def fetch_stars(slug, token):
    req = urllib.request.Request(
        f"https://api.github.com/repos/{slug}",
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": "jumponthemoon.github.io-star-fetch",
            **({"Authorization": f"Bearer {token}"} if token else {}),
        },
    )
    with urllib.request.urlopen(req, timeout=20) as resp:
        return json.load(resp)["stargazers_count"]


def main():
    token = os.environ.get("GITHUB_TOKEN", "")
    slugs = repos_in_bibliography(BIB)
    if not slugs:
        print("no GitHub repos found in the bibliography", file=sys.stderr)
        return 0

    stars, failed = {}, []
    for slug in slugs:
        try:
            stars[slug] = fetch_stars(slug, token)
        except (urllib.error.URLError, KeyError, TimeoutError) as exc:
            # A missing count just hides that badge; never fail the build over it.
            failed.append(f"{slug}: {exc}")

    lines = [
        "# Generated by bin/fetch_github_stars.py -- do not edit by hand.",
        "# Refreshed automatically on every deploy.",
    ]
    lines += [f'"{slug}": {count}' for slug, count in sorted(stars.items())]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"wrote {len(stars)} star counts to {os.path.relpath(OUT, ROOT)}")
    for line in failed:
        print(f"  skipped {line}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
